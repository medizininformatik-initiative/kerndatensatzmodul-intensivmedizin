#!/usr/bin/env python3
"""Pages for the ISiK-hosted ICU profiles, rendered inside this IG.

The Monitoring and Vital Signs profiles of this module (sd-mii-icu-*) are
maintained by gematik in the package de.gematik.isik. The IG Publisher only
renders profiles that belong to the IG itself, so the build renders them with
Gefyra/ig-external-profiles-action: a helper IG produces the Publisher's own
fragments (differential, snapshot, must support, definitions) and writes them
to input/includes/extern-<id>.*. No ISiK StructureDefinition enters this
repository or this IG's package; only the HTML rendering does.

This script keeps the committed inputs of that step in sync with the pinned
package version (pin read from sushi-config.yaml, content from
~/.fhir/packages/de.gematik.isik#<pin>):

  * external-profiles.yaml          the action's configuration
  * input/pagecontent/extern-<id>.md and its German mirror under
    input/translations/de/pagecontent/  one page per profile
  * the generated block of page entries under profiles.md in sushi-config.yaml

Like the profile list on profiles.md (scripts/gen-profile-map.py), the set of
pages changes only with a deliberate pin bump.

Usage:  python3 scripts/gen-external-profiles.py          # write
        python3 scripts/gen-external-profiles.py --check  # fail on drift
"""
import argparse
import glob
import json
import os
import re
import sys

# ISiK-hosted profiles that do not follow the sd-mii-icu-* naming.
EXTRA_IDS = ['mii-pr-icu-muv-zerebraler-perfusionsdruck']

# Original pages: gematik publishes the ICU part of ISiK as its own IG.
ORIGINAL = 'https://gemspec.gematik.de/ig/fhir/isik/icu/{pin}/StructureDefinition-{id}.html'

CONFIG = 'external-profiles.yaml'
PAGES = {'en': 'input/pagecontent', 'de': 'input/translations/de/pagecontent'}
BEGIN = '    # BEGIN generated: ISiK-hosted profile pages (scripts/gen-external-profiles.py)'
END = '    # END generated: ISiK-hosted profile pages'


def isik_pin():
    m = re.search(r'^\s*de\.gematik\.isik:\s*(\S+)', open('sushi-config.yaml').read(), re.M)
    if not m:
        sys.exit('ERROR: no de.gematik.isik pin in sushi-config.yaml')
    return m.group(1)


def load_profiles(pin):
    base = os.path.expanduser(f'~/.fhir/packages/de.gematik.isik#{pin}/package')
    if not os.path.isdir(base):
        sys.exit(f'ERROR: ISiK package not in the cache: {base}\n'
                 '(prime the cache, see README section "Lokaler Build")')
    out = {}
    files = glob.glob(f'{base}/StructureDefinition-sd-mii-icu-*.json')
    files += [f'{base}/StructureDefinition-{i}.json' for i in EXTRA_IDS]
    for f in files:
        if not os.path.exists(f):
            sys.exit(f'ERROR: {f} missing from the ISiK package')
        d = json.load(open(f))
        out[d['id']] = d.get('title') or d.get('name') or d['id']
    return dict(sorted(out.items()))


def render_config(pin, profiles):
    lines = [
        '# Generated by scripts/gen-external-profiles.py - do not edit by hand.',
        '# Renders the ISiK-hosted ICU profiles on pages of this IG with',
        '# Gefyra/ig-external-profiles-action (see .github/workflows/ig-publisher.yml).',
        'profiles:',
    ]
    for pid in profiles:
        lines += [
            f'  - id: {pid}',
            f'    package: de.gematik.isik#{pin}',
            f'    page: extern-{pid}.html',
            f'    link: {ORIGINAL.format(pin=pin, id=pid)}',
        ]
    lines += [
        'output: input/includes',
        'data: input/data',
    ]
    return '\n'.join(lines) + '\n'


def render_page(pid):
    return ('<!-- markdownlint-disable MD041 -->\n'
            '<!-- Generated by scripts/gen-external-profiles.py. The include is written by the build '
            '(Gefyra/ig-external-profiles-action) from the pinned de.gematik.isik package. -->\n'
            f'{{% include extern-{pid}.html %}}\n')


def render_sushi_block(profiles):
    lines = [BEGIN]
    for pid, title in profiles.items():
        lines += [f'    extern-{pid}.md:', f'      title: "{title}"']
    lines.append(END)
    return '\n'.join(lines)


def with_sushi_block(text, block):
    if BEGIN in text:
        return re.sub(re.escape(BEGIN) + r'.*?' + re.escape(END), lambda _: block, text, flags=re.S)
    anchor = '  profiles.md:\n    title: Profiles\n'
    if anchor not in text:
        sys.exit('ERROR: profiles.md entry not found under pages: in sushi-config.yaml')
    return text.replace(anchor, anchor + block + '\n', 1)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true', help='fail if the committed files are out of date')
    args = ap.parse_args()

    pin = isik_pin()
    profiles = load_profiles(pin)

    wanted = {CONFIG: render_config(pin, profiles)}
    for d in PAGES.values():
        for pid in profiles:
            wanted[f'{d}/extern-{pid}.md'] = render_page(pid)
    sushi = open('sushi-config.yaml').read()
    wanted['sushi-config.yaml'] = with_sushi_block(sushi, render_sushi_block(profiles))

    stale = [f for d in PAGES.values() for f in glob.glob(f'{d}/extern-*.md') if f not in wanted]
    drift = [p for p, c in wanted.items() if not os.path.exists(p) or open(p).read() != c]

    if args.check:
        if drift or stale:
            sys.exit('ERROR: external profile pages out of date, run scripts/gen-external-profiles.py\n  '
                     + '\n  '.join(drift + [f'{s} (stale)' for s in stale]))
        print(f'OK: {len(profiles)} ISiK {pin} profiles, pages in sync')
        return
    for p in drift:
        with open(p, 'w') as fh:
            fh.write(wanted[p])
    for s in stale:
        os.remove(s)
    print(f'{len(profiles)} ISiK {pin} profiles: {len(drift)} file(s) written, {len(stale)} removed')


if __name__ == '__main__':
    main()
